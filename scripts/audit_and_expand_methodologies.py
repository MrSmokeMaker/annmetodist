def audit_and_expand():
    topics_paths = [
        'assets/assets/data/topics.json',
        'assets/data/topics.json'
    ]

    primary_path = topics_paths[0]
    with open(primary_path, 'r', encoding='utf-8') as f:
        existing_topics = json.load(f)

    print(f"Исходное количество тем в базе: {len(existing_topics)}")

    existing_titles = {t['title'].lower().strip() for t in existing_topics}
    existing_by_method = {}
    for t in existing_topics:
        m = t.get('methodId')
        existing_by_method.setdefault(m, []).append(t)

    new_topics = []
    audit_findings = []

    # Check each method
    for method_id, age_groups in CANONICAL_EXTENSIONS.items():
        current_count = len(existing_by_method.get(method_id, []))
        added_for_method = 0

        for age_group, topics_list in age_groups.items():
            for t_data in topics_list:
                title = t_data['title']
                if title.lower().strip() not in existing_titles:
                    # Generate unique ID
                    suffix = str(current_count + added_for_method + 1).zfill(2)
                    ag_prefix = "pre" if age_group == "preschool" else ("g1" if age_group == "grade_1" else "g2")
                    m_short = method_id.split('_')[0]
                    new_id = f"{m_short}_{ag_prefix}_{suffix}"

                    new_topic = {
                        "id": new_id,
                        "methodId": method_id,
                        "ageGroup": age_group,
                        "title": title,
                        "description": t_data['description']
                    }
                    new_topics.append(new_topic)
                    existing_titles.add(title.lower().strip())
                    added_for_method += 1

        audit_findings.append({
            "methodId": method_id,
            "previousCount": current_count,
            "addedCount": added_for_method,
            "newTotal": current_count + added_for_method
        })

    print(f"\n=======================================================")
    print(f"  РЕЗУЛЬТАТЫ АУДИТА МЕТОДИК И ПОИСКА НЕДОСТАЮЩИХ ТЕМ")
    print(f"=======================================================")
    for af in audit_findings:
        print(f"• {af['methodId']}: было {af['previousCount']} тем -> добавлено {af['addedCount']} недостающих тем -> стало {af['newTotal']}")

    total_added = len(new_topics)
    print(f"\nИТОГО найдено и добавлено недостающих тем: {total_added}")
    print(f"Новое общее количество тем в базе: {len(existing_topics) + total_added}")

    if total_added > 0:
        updated_topics = existing_topics + new_topics
        for p in topics_paths:
            if os.path.exists(p):
                with open(p, 'w', encoding='utf-8') as f:
                    json.dump(updated_topics, f, ensure_ascii=False, indent=2)
                print(f"[OK] Обновлен файл: {p}")

        # Write audit report
        os.makedirs('docs', exist_ok=True)
        report_path = 'docs/missing_topics_audit_report.md'
        with open(report_path, 'w', encoding='utf-8') as f:
            f.write("# Отчёт аудита существующих методик и добавления недостающих тем\n\n")
            f.write("Настоящий аудит проведён в рамках перехода на **полный академический охват учебных курсов авторов**.\n")
            f.write("Сняты искусственные лимиты: все недостающие канонические темы учебников Пчёлко, Костина, Редозубова, Боголюбова, Мазиной, Чаплыгина и Косиновой включены в дидактическую базу.\n\n")
            f.write("| Методика | Предыдущее кол-во | Добавлено недостающих | Итого тем в курсе |\n")
            f.write("| :--- | :---: | :---: | :---: |\n")
            for af in audit_findings:
                f.write(f"| `{af['methodId']}` | {af['previousCount']} | +{af['addedCount']} | **{af['newTotal']}** |\n")
            f.write(f"\n**Всего тем в системе:** {len(existing_topics) + total_added} (было {len(existing_topics)})\n\n")

            f.write("## 📝 Список добавленных канонических тем по разделам:\n\n")
            for t in new_topics:
                f.write(f"- **[{t['methodId']} | {t['ageGroup']}]** `{t['id']}`: **{t['title']}**\n")
                f.write(f"  *{t['description']}*\n\n")

        print(f"[OK] Подробный отчёт аудита сохранён: {report_path}")
    else:
        print("Все канонические темы уже присутствуют в базе данных.")


if __name__ == '__main__':
    audit_and_expand()
