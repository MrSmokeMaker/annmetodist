class NumberedRussianCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super(NumberedRussianCanvas, self).__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super(NumberedRussianCanvas, self).showPage()
        super(NumberedRussianCanvas, self).save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        page_w, page_h = A4
        
        # Header (pages 2+)
        if self._pageNumber > 1:
            self.setFillColor(colors.HexColor('#9A3412')) # Terracotta-brown
            self.rect(36, page_h - 32, page_w - 72, 2, fill=True, stroke=False)
            self.setFont('Nunito-Bold', 8)
            self.setFillColor(colors.HexColor('#7C2D12'))
            self.drawString(36, page_h - 26, "КОНСПЕКТ ЗАНЯТИЯ ПО РУССКОМУ ЯЗЫКУ • 2 КЛАСС")
            self.setFont('Nunito', 8)
            self.setFillColor(colors.HexColor('#78716C'))
            self.drawRightString(page_w - 36, page_h - 26, "Тема: «Что такое окончание» (методика Н. А. Костина)")

        # Footer
        self.setFillColor(colors.HexColor('#E7E5E4'))
        self.rect(36, 30, page_w - 72, 1, fill=True, stroke=False)
        self.setFont('Nunito', 8)
        self.setFillColor(colors.HexColor('#78716C'))
        self.drawString(36, 20, "Классическая советская методика начальной школы • Н. А. Костин (1949)")
        page_str = f"Страница {self._pageNumber} из {page_count}"
        self.drawRightString(page_w - 36, 20, page_str)
        self.restoreState()

