class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super(NumberedCanvas, self).__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super(NumberedCanvas, self).showPage()
        super(NumberedCanvas, self).save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        page_w, page_h = A4
        
        # Header (pages 2+)
        if self._pageNumber > 1:
            self.setFillColor(colors.HexColor('#4F46E5'))
            self.rect(36, page_h - 32, page_w - 72, 2, fill=True, stroke=False)
            self.setFont('Nunito-Bold', 8)
            self.setFillColor(colors.HexColor('#4338CA'))
            self.drawString(36, page_h - 26, "КОНСПЕКТ УРОКА МАТЕМАТИКИ • 1 КЛАСС")
            self.setFont('Nunito', 8)
            self.setFillColor(colors.HexColor('#6B7280'))
            self.drawRightString(page_w - 36, page_h - 26, "Сложение и вычитание с переходом через десяток (Пчёлко А.С., Поляк Г.В.)")

        # Footer
        self.setFillColor(colors.HexColor('#E2E8F0'))
        self.rect(36, 30, page_w - 72, 1, fill=True, stroke=False)
        self.setFont('Nunito', 8)
