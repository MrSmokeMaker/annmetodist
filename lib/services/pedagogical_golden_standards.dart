/// Библиотека «Золотых эталонов» отечественной педагогики (Few-Shot RAG-инъекции).
/// Содержит живые образцы сократовского диалога, работы над ошибками и драматургии
/// для математики, русского языка, окружающего мира и дошкольного развития.
class PedagogicalGoldenStandards {
  /// Получить эталонный фрагмент урока по предмету и методике
  static String getGoldenStandard({
    required String subject,
    String? methodId,
    String? ageGroup,
  }) {
    final sub = subject.toLowerCase();

    if (sub.contains('матем') || sub.contains('счет') || sub.contains('числ') || methodId == 'peterson_math' || methodId == 'singapore_cpa') {
      return mathPetersonStandard;
    } else if (sub.contains('русск') || sub.contains('грамот') || sub.contains('чтен') || sub.contains('язык') || methodId == 'mazina_calligraphy') {
      return russianLanguageStandard;
    } else if (sub.contains('окруж') || sub.contains('природ') || sub.contains('мир') || methodId == 'zankov_exploration') {
      return worldExplorationStandard;
    } else {
      return preschoolTrizStandard;
    }
  }

  /// Эталон 1: Математика (Петерсон / Пчёлко) — Открытие состава числа через проблемную ситуацию
  static const String mathPetersonStandard = '''
[ЗОЛОТОЙ ЭТАЛОН ПЕДАГОГИЧЕСКОГО ДИАЛОГА: МАТЕМАТИКА]
Учитель: "Ребята, посмотрите на наш волшебный числовой домик. На крыше живёт число 7. В левом окошке зажёгся огонёк — там поселилось число 4. Сколько жильцов спряталось в правом окошке?"
Дети хором: "Три!"
Учитель: "А как вы догадались, юные математики? Кто объяснит ход своей мысли?"
Миша: "Потому что 7 — это 4 да ещё 3!"
Учитель (сократовский перехват сомнения): "А вот Незнайка шепчет мне на ушко, что в правом окошке живёт 2. Давайте проверим гипотезу Незнайки на числовом луче. Если мы к 4 прибавим 2, куда мы прискачем?"
Аня: "Мы попадём в точку 6, а нам нужно в 7!"
Учитель: "Какой же шаг нужно сделать от 6 до 7?"
Класс: "Ещё один шаг! Значит, нужно было прибавить не 2, а 3!"
Учитель: "Великолепно! Зафиксируем наш математический секрет на доске: 7 = 4 + 3."
''';

  /// Эталон 2: Русский язык (Мазина / Костин) — Орфографическая зоркость и звуковой анализ
  static const String russianLanguageStandard = '''
[ЗОЛОТОЙ ЭТАЛОН ПЕДАГОГИЧЕСКОГО ДИАЛОГА: РУССКИЙ ЯЗЫК]
Учитель: "Произнесём хором слово 'гриб' так, как мы его говорим в живой речи: 'гри-п'. Какой звук слышится на самом конце слова?"
Дети: "Глухой звук [п]!"
Учитель: "Верно, звук [п] надел маску-невидимку. Но какую же букву нам доверить написать в тетради — букву Пэ или Бэ?"
Коля: "Наверное, Пэ, ведь слышно же [п]!"
Учитель: "Коля высказал очень естественную мысль. Но согласны ли наши буквенные детективы? Как нам сорвать маску с хитрого звука?"
Лена: "Нужно позвать волшебников — гласные звуки! Изменим слово так, чтобы после согласного стоял гласный: 'много...' — грибов! Или ласково: 'маленький...' — грибок!"
Учитель: "И какой звук зазвенел во весь голос перед гласным?"
Класс: "Звонкий [б]!"
Учитель: "Значит, в слове 'гриб' пишется буква 'б', а на конце происходит оглушение. Запомним наше золотое правило: 'Гласный звук позвал согласный — и секрет открылся ясный!'."
''';

  /// Эталон 3: Окружающий мир (Занков / Виноградова) — Исследование и научное наблюдение
  static const String worldExplorationStandard = '''
[ЗОЛОТОЙ ЭТАЛОН ПЕДАГОГИЧЕСКОГО ДИАЛОГА: ОКРУЖАЮЩИЙ МИР]
Учитель: "Посмотрите на две веточки в наших стаканах: одна стояла на светлом подоконнике, а вторая — в темном шкафу. Что произошло с их листочками?"
Серёжа: "У той, что в шкафу, листочки бледные и жёлтые, а на подоконнике — сочные и ярко-зелёные!"
Учитель: "Какую научную гипотезу мы можем выдвинуть? Что требуется маленькому растению для создания зелёной краски хлорофилла?"
Даша: "Солнечный свет!"
Учитель: "А если бы растение жило в пустыне, где солнца слишком много? Давайте потрогаем толстые листочки нашего кактуса. Почему они похожи на бочонки?"
Дети: "Они запасают воду, чтобы не засохнуть!"
Учитель: "Блестящий вывод юных исследователей! Занесем наше наблюдение в путевой журнал открытий."
''';

  /// Эталон 4: Дошкольное развитие и ТРИЗ (Выготский / Венгер) — Образность и сказка
  static const String preschoolTrizStandard = '''
[ЗОЛОТОЙ ЭТАЛОН ПЕДАГОГИЧЕСКОГО ДИАЛОГА: ДОШКОЛЬНИКИ И ТРИЗ]
Воспитатель: "Ребята, Медвежонок спешил на день рождения к Совёнку и нёс кувшин с компотом. Но на тропинке упал камушек, кувшин треснул, а чашек с собой нет! Как Медвежонку донести компот, не потеряв ни капельки?"
Ваня: "Заморозить его в морозилке, чтобы он стал как льдинка на палочке!"
Маша: "Свернуть большой лист лопуха кулёчком, как стаканчик!"
Воспитатель: "Какая богатая фантазия у наших изобретателей! А теперь давайте наши пальчики превратятся в маленьких волшебников: погладим ладошки, согреем их и покажем, как капает весёлый дождик (пальчиковая нейрогимнастика)..."
''';
}
