        'Ответ: "Можно, но тогда твои мысли могут понять неправильно"',
      ]);
    } else if (subject == 'Математика') {
      questions.addAll([
        'Вопрос: "Зачем мне это считать?"',
        'Ответ: "Чтобы знать, сколько конфет можно купить на карманные деньги"',
        '',
        'Вопрос: "Когда это пригодится?"',
        'Ответ: "Когда будешь планировать свои дела или играть в игры"',
      ]);
    } else {
      questions.addAll([
        'Вопрос: "Это сложно?"',
