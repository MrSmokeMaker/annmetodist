  /// Получить объяснение темы для конкретной возрастной группы
  static String? getExplanation(String subject, String topic, String ageGroup) {
    final Map<String, Map<String, String>> explanations;
    
    switch (subject) {
      case 'Русский язык':
        explanations = _russianLanguageExplanations;
        break;
      case 'Математика':
        explanations = _mathExplanations;
        break;
      case 'Обучение чтению':
      case 'Чистописание':
        explanations = _readingExplanations;
        break;
      default:
        explanations = _russianLanguageExplanations;
    }
    
    final ageGroupExplanations = explanations[ageGroup] ?? explanations['grade_1']!;
    return ageGroupExplanations[topic.toLowerCase()];
  }

  /// Создать полное объяснение темы с примерами
  static String createCompleteExplanation(String subject, String topic, String ageGroup) {
    final baseExplanation = getExplanation(subject, topic, ageGroup) ?? 
        'Объяснение темы "$topic" будет доступно в процессе занятия.';
    
    final examples = _generateExamples(subject, topic, ageGroup);
    final activities = _generateActivities(subject, topic, ageGroup);
    final commonQuestions = _generateCommonQuestions(subject, topic, ageGroup);
    
    return '''
# Как объяснить тему "$topic" ребенку ($ageGroup)

## Простое объяснение:
$baseExplanation

## Примеры из жизни:
${examples.join('\n')}

## Чем можно заняться:
${activities.join('\n')}

## Ответы на частые вопросы ребенка:
${commonQuestions.join('\n')}

## Советы родителям:
- Будьте терпеливы, если ребенок не понимает сразу
- Используйте наглядные материалы и игрушки
- Хвалите за любую попытку понять
- Превращайте обучение в игру
- Связывайте тему с интересами ребенка
''';
  }

  /// Сгенерировать примеры для темы
  static List<String> _generateExamples(String subject, String topic, String ageGroup) {
    final examples = <String>[];
    
    if (subject == 'Русский язык' && topic.toLowerCase().contains('гласные')) {
      examples.addAll([
        '- В слове "МАМА" гласные А-А говорят "а-а"',
        '- В слове "КОТ" гласная О говорит "о-о"',
        '- Поиграйте: хлопайте в ладоши на каждый гласный звук в слове',
      ]);
    } else if (subject == 'Математика' && topic.toLowerCase().contains('сложение')) {
      examples.addAll([
        '- У тебя 2 красных машинки и 3 синих. Сколько всего машинок? 2+3=5',
        '- На тарелке 4 печенья, положили ещё 2. Сколько стало? 4+2=6',
        '- У Пети 1 яблоко, у Маши 2 яблока. Вместе у них 1+2=3 яблока',
      ]);
    } else {
      examples.addAll([
        '- Приведите пример из повседневной жизни ребенка',
        '- Используйте игрушки для наглядности',
        '- Создайте ситуацию, где нужно применить знания',
      ]);
    }
    
    return examples;
  }

  /// Сгенерировать активности для темы
  static List<String> _generateActivities(String subject, String topic, String ageGroup) {
    final activities = <String>[];
    
    if (ageGroup == 'preschool') {
      activities.addAll([
        '- Лепить буквы/цифры из пластилина',
        '- Рисовать на песке или манке',
        '- Играть в подвижные игры на тему',
        '- Раскрашивать картинки по теме',
      ]);
    } else if (ageGroup == 'grade_1') {
      activities.addAll([
        '- Решать простые задачки',
        '- Составлять слова из кубиков',
        '- Играть в настольные игры по теме',
        '- Делать простые проекты',
      ]);
    } else {
      activities.addAll([
        '- Решать более сложные задачи',
        '- Читать книги по теме',
        '- Создавать свои задания',
        '- Участвовать в викторинах',
      ]);
    }
    
    return activities;
  }

