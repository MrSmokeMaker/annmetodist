/// Сервис с готовыми шаблонами объяснений сложных тем простым языком для детей.
/// Предоставляет глубокое объяснение, осязаемые метафоры, анти-заблуждения,
/// сценарии уроков и эталонные дидактические материалы для всех 173 тем приложения.
class PedagogicalPackage {
  final String category;
  final String essence;
  final List<String> metaphors;
  final String misconception;
  final String rule;
  final String dialogueScript;
  final List<String> tableHeaders;
  final List<String> wordBank;
  final String neznaykaMistake;
  final String neznaykaCorrection;
  final Map<String, String> cipherKey;
  final String cipherCode;
  final String cipherAnswer;
  final String trizChallenge;
  final List<String> trizWords;
  final String trizAnswer;
  final String calligraphyElements;
  final String teacherAnswers;

  const PedagogicalPackage({
    required this.category,
    required this.essence,
    required this.metaphors,
    required this.misconception,
    required this.rule,
    required this.dialogueScript,
    required this.tableHeaders,
    required this.wordBank,
    required this.neznaykaMistake,
    required this.neznaykaCorrection,
    required this.cipherKey,
    required this.cipherCode,
    required this.cipherAnswer,
    required this.trizChallenge,
    required this.trizWords,
    required this.trizAnswer,
    required this.calligraphyElements,
    required this.teacherAnswers,
  });
}

class TopicExplanationService {
  /// Получить структурированный педагогический пакет по теме, предмету и классу.
  static PedagogicalPackage getPedagogicalPackage(String subject, String topic, String ageGroup) {
    final category = _matchCategory(topic, subject);
    return _buildPackage(category, topic, ageGroup);
  }

  /// Получить текстовое объяснение темы (для совместимости со старым кодом)
  static String? getExplanation(String subject, String topic, String ageGroup) {
    return getPedagogicalPackage(subject, topic, ageGroup).essence;
  }

  /// Создать полное методическое объяснение темы с примерами
  static String createCompleteExplanation(String subject, String topic, String ageGroup) {
    final pkg = getPedagogicalPackage(subject, topic, ageGroup);
    return '''
# Как объяснить тему "$topic" ($ageGroup)

## Глубокая суть темы:
${pkg.essence}

## Осязаемые метафоры для детей:
${pkg.metaphors.map((m) => '- $m').join('\n')}

## Главное правило урока:
${pkg.rule}

## Ловушка внимания (анти-заблуждение):
${pkg.misconception}

## Образец живого диалога учителя и учеников:
${pkg.dialogueScript}
''';
  }

  /// Популярные темы для предмета
  static List<String> getPopularTopics(String subject, String ageGroup) {
    final s = subject.toLowerCase();
    if (s.contains('русск')) {
      return ['Гласные и согласные звуки', 'Слог и ударение', 'Мягкий знак', 'Большая буква', 'Безударные гласные', 'Корень слова'];
    } else if (s.contains('матем')) {
      return ['Состав чисел первого десятка', 'Сложение и вычитание в пределах 10', 'Понятие об арифметической задаче', 'Переход через десяток', 'Смысл умножения'];
    } else if (s.contains('чтен')) {
      return ['Звуковой анализ слов', 'Механизм слияния по Редозубову', 'Открытые и закрытые слоги', 'Йотированные гласные', 'Беглое выразительное чтение'];
    } else if (s.contains('чистопис') || s.contains('письм')) {
      return ['Посадка и наклон 65°', 'Генетические группы букв', 'Элементы Мазиной (качалочка, секретик)', 'Безотрывное соединение'];
    }
    return ['Звуки и буквы', 'Счет предметов', 'Слоги и слова'];
  }

  static String _matchCategory(String topic, String subject) {
    final t = topic.toLowerCase();
    final s = subject.toLowerCase();

    // 1. Русский язык
    if (RegExp(r'звук.*букв|гласн.*согласн|звуки вокруг|органы речи|перв.*звук').hasMatch(t)) return 'ru_sounds_letters';
    if (RegExp(r'слог|ударен|перенос').hasMatch(t)) return 'ru_syllables_stress';
    if (RegExp(r'тв[её]рд.*мягк|е, ё, и, ю, я|второго ряда').hasMatch(t)) return 'ru_hard_soft';
    if (RegExp(r'мягк.*знак|разделительн.*знак').hasMatch(t)) return 'ru_soft_sign';
    if (RegExp(r'больш.*букв|заглавн').hasMatch(t)) return 'ru_capital_letter';
    if (RegExp(r'жи-ши|ча-ща|чу-щу|чк|чн|щн|шипящ').hasMatch(t)) return 'ru_spelling_rules';
    if (RegExp(r'корен|однокорен|родствен|ласков.*значени|словообразован').hasMatch(t)) return 'ru_word_root';
    if (RegExp(r'безударн').hasMatch(t)) return 'ru_unstressed_vowels';
    if (RegExp(r'парн.*согласн|оглушен').hasMatch(t)) return 'ru_paired_consonants';
    if (RegExp(r'непроизносим').hasMatch(t)) return 'ru_unpronounceable_consonants';
    if (RegExp(r'предлог').hasMatch(t)) return 'ru_prepositions';
    if (RegExp(r'существительн|названия предмет|одушевлен').hasMatch(t)) return 'ru_noun';
    if (RegExp(r'глагол|действи').hasMatch(t)) return 'ru_verb';
    if (RegExp(r'прилагательн|признак').hasMatch(t)) return 'ru_adjective';
    if (RegExp(r'согласование слов|в роде|в числе').hasMatch(t)) return 'ru_grammar_agreement';
    if (RegExp(r'предложени|текст|изложени|речь').hasMatch(t)) return 'ru_sentence_text';

    // 2. Математика
    if (RegExp(r'размер|большой.*маленький|длинный.*короткий|пространств|выше.*ниже|справа|слева|впереди|сзади').hasMatch(t)) return 'math_spatial_size';
    if (RegExp(r'поровну|столько же|количествен').hasMatch(t)) return 'math_quantitative';
    if (RegExp(r'числа.*1.*5|числа.*6.*10|состав чисел|счет.*предел.*5|счет.*предел.*10|перв.*десят').hasMatch(t)) return 'math_numbers_composition';
    if (RegExp(r'число 0|действия с нулем|нол').hasMatch(t)) return 'math_zero';
    if (RegExp(r'сложение и вычитание.*10|на основе.*состава чисел|переместительное свойство').hasMatch(t)) return 'math_addition_subtraction_10';
    if (RegExp(r'понятие об арифметической задаче|условие, вопрос').hasMatch(t)) return 'math_problem_concept';
    if (RegExp(r'на сколько больше|увеличени.*уменьшени.*числа|разностн.*сравнен').hasMatch(t)) return 'math_comparison_problems';
    if (RegExp(r'второй десяток|нумерация.*11.*20|сложение и вычитание без перехода').hasMatch(t)) return 'math_second_decade';
    if (RegExp(r'дециметр|сантиметр|измерение отрезков|длин').hasMatch(t)) return 'math_length_units';
    if (RegExp(r'переход.*десят|9 \+ 2|11 - 2|табличное вычитание').hasMatch(t)) return 'math_transition_decade';
    if (RegExp(r'нумерация.*100|разряды десятков|двузначн').hasMatch(t)) return 'math_numbers_100';
    if (RegExp(r'составные задачи|в два действия').hasMatch(t)) return 'math_two_step_problems';
    if (RegExp(r'смысл.*умножени|таблица умножени').hasMatch(t)) return 'math_multiplication';
    if (RegExp(r'делени').hasMatch(t)) return 'math_division';
    if (RegExp(r'порядок.*действи|скобк').hasMatch(t)) return 'math_order_operations';

    // 3. Обучение чтению и логопедия
    if (RegExp(r'живое звучащее|артикуляц.*гласн|выделение.*гласн|звуковой анализ слияния|выделение первого').hasMatch(t)) return 'read_sound_analysis';
    if (RegExp(r'механизм слияния|буква м|звук.*буква').hasMatch(t)) return 'read_blending';
    if (RegExp(r'открытых и закрытых слогов|трех букв|двухсложных|шар, сыр|ма-ма').hasMatch(t)) return 'read_syllables_words';
    if (RegExp(r'йотирован|е, ё, ю, я|два звука').hasMatch(t)) return 'read_iotated';
    if (RegExp(r'стечением.*согласных|стол, волк').hasMatch(t)) return 'read_clusters';
    if (RegExp(r'беглое|логическое ударение|ролевое чтение|смысловой анализ|выразительн|антиципаци').hasMatch(t)) return 'read_fluent';
    if (RegExp(r'кубик.*вращени|кубик.*слог|превращение слога').hasMatch(t)) return 'chaplygin_rotation';
    if (RegExp(r'кубик.*первых слов|разных слогов|закрытый слог|словарные эстафеты|превращение слов|трех.*четырехсложных|тахистоскоп').hasMatch(t)) return 'chaplygin_words';
    if (RegExp(r'артикуляционная гимнастика|заборчик|трубочка|лопатка|речевое дыхание|ветерок').hasMatch(t)) return 'kosinova_articulation';
    if (RegExp(r'поймай звук|место звука|звуковой поезд').hasMatch(t)) return 'kosinova_phonemic';
    if (RegExp(r'дифференциация|б-п|д-т|г-к|в-ф|з-с|ж-ш|свистящ|шипящ|\[р\].*\[л\]|звонких и глухих').hasMatch(t)) return 'kosinova_differentiation';

    // 4. Чистописание и каллиграфия
    if (RegExp(r'посадка|захват карандаша|гигиеническ|подготовка руки|нажим пера').hasMatch(t)) return 'pen_hygiene_grip';
    if (RegExp(r'наклонн.*линии.*65|закруглением внизу|частая косая|ориентиры|ритм связного безотрывного').hasMatch(t)) return 'pen_slant_grid';
    if (RegExp(r'генетическая группа|букв.*и, ш, г|букв.*л, м|букв.*о, с|петлями|перекладинами|соединений|сложной конфигурации|домик для звука|соединени.*букв|дисграфи|различение букв').hasMatch(t)) return 'pen_letter_groups';
    if (RegExp(r'заглавные буквы.*групп|пропорции|ритмическое.*письмо|исправление.*ошибок').hasMatch(t)) return 'pen_capitals';
    if (RegExp(r'нейроразминк|гипертонус|бордюров в крупной клетке|узоры в воздухе|снятие напряжения|нейрогимнастик|спазм|сброс капелек').hasMatch(t)) return 'pen_mazina_neuro';
    if (RegExp(r'качалочк|секретик|крючок до середины|алгоритм.*наклонная|соединение элементов').hasMatch(t)) return 'pen_mazina_elements';
    if (RegExp(r'овал и полукруг|межбуквенных|широкой косой|микрографи|скоропись|скорость письма|самопроверка почерка').hasMatch(t)) return 'pen_mazina_advanced';

    if (s.contains('матем')) return 'math_addition_subtraction_10';
    if (s.contains('чтен')) return 'read_sound_analysis';
    if (s.contains('чистопис') || s.contains('письм')) return 'pen_slant_grid';
    return 'ru_sounds_letters';
  }

