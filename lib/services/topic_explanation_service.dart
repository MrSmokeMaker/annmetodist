  static List<String> getPopularTopics(String subject, String ageGroup) {
    final Map<String, Map<String, String>> explanations;
    
    switch (subject) {
      case 'Русский язык':
        explanations = _russianLanguageExplanations;
        break;
      case 'Математика':
        explanations = _mathExplanations;
        break;
      case 'Обучение чтению':
      case 'Чистописание':
        explanations = _readingExplanations;
        break;
      default:
        return [];
    }
    
    final ageGroupExplanations = explanations[ageGroup] ?? explanations['grade_1']!;
    return ageGroupExplanations.keys.toList();
  }
