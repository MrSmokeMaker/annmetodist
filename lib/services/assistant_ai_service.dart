/// Тип сообщения в чате с Совёнком
enum AssistantSender {
  user,
  assistant,
  system,
}

/// Педагогические режимы работы Совёнка
enum AssistantMode {
  academic('🎓 Академический', 'ФГОС, СанПиН, классика Пчёлко/Костина и методическая строгость'),
  gamification('🎮 Игропрактик', 'Сюжетные квесты, интриги, маскоты и механики 5 миров'),
  parentChat('💬 Родительский чат', 'Доброжелательные, ёмкие посты для родителей с советами'),
  triz('🧩 ТРИЗ и эвристика', 'Проблемные противоречия, парадоксы и ловушки Незнайки'),
  homework('📚 Дифференциатор ДЗ', '3 уровня домашнего задания: базовый, продвинутый, олимпиадный');

  final String label;
  final String description;
  const AssistantMode(this.label, this.description);
}

/// Сообщение в чате AI-помощника
class AssistantMessage {
  final String id;
  final AssistantSender sender;
  final String text;
  final DateTime timestamp;
  final String? actionType; // 'insert_snippet', 'change_world', 'export_pdf', 'copy_parent'
  final String? actionPayload;

  AssistantMessage({
    required this.id,
    required this.sender,
    required this.text,
    required this.timestamp,
    this.actionType,
    this.actionPayload,
  });
}

