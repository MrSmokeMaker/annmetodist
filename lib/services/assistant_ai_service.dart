> *«Ребята! В мире ${world.title} зашифрован секретный артефакт Знаний. Чтобы открыть ларец, ${world.mascotName} должен пройти 3 испытания по нашей теме "$topic". Поможем нашему другу?»*

🎯 **Этап 1: «Входные ворота» (Фронтальный опрос, 3 мин):**  
Учитель задаёт 3 быстрых вопроса. Каждый правильный ответ хором открывает одну створку ворот.

⚡ **Этап 2: «Лабиринт смекалки» (Парная работа, 4 мин):**  
Каждая парта получает шифр-задание по теме «$topic». Задача — расшифровать ключевое слово и поднять карточку готовности.

🏆 **Этап 3: «Ключ Мудрости» (Рефлексия, 3 мин):**  
Маскот благодарит ребят, ларец открывается! Внутри — звёзды успеха и формула главного правила урока.
''';
    }

    // 4. Экспресс-тест с ключами проверки
    if (lower.contains('тест') || lower.contains('срез') || lower.contains('опрос') || lower.contains('ключ')) {
      return '''
🦉 **Экспресс-тест проверки знаний (3-5 минут)**

*Тема:* **«$topic»**

**Вопрос 1 (Базовый факт):**  
Какое утверждение о теме «$topic» является верным?  
А) Это правило применяется только в исключительных случаях  
Б) Это основной алгоритм проверки и решения  
В) Это устаревшее понятие  
*(Правильный ответ: Б)*

**Вопрос 2 (Практическое применение):**  
Найдите верную последовательность действий при решении задачи:  
А) Записать ответ → прочитать условие  
Б) Прочитать условие → выделить главное → решить → проверить  
В) Спросить соседа  
*(Правильный ответ: Б)*

**Вопрос 3 (Логический вопрос на смекалку):**  
Что произойдёт, если изменить одно из ключевых условий в теме «$topic»? Объясните кратко своими словами.

🔑 **Критерии оценивания:**  
- 3 верных ответа — ⭐⭐⭐ (Уровень «Магистр»)  
- 2 верных ответа — ⭐⭐ (Уровень «Исследователь»)  
- 1 верный ответ — ⭐ (Рекомендуется повторить правило с карточкой)
''';
    }

    // 5. Вводное слово учителя (2 минуты)
    if (lower.contains('вводн') || lower.contains('вступлен') || lower.contains('начало') || lower.contains('мотивац') || lower.contains('слово')) {
      return '''
🦉 **Вдохновляющее вводное слово учителя (первые 2 минуты урока)**

*Тема:* **«$topic»**  
*Игровой мир:* **${world.title}**

*(Учитель выдерживает короткую паузу, улыбается и обращается к классу):*

> «Здравствуйте, юные исследователи!  
> Посмотрите сегодня в окно и вокруг себя в классе. Знаете ли вы, что прямо сейчас мы окружены невидимыми законами порядка и логики?  
> Сегодня наш маскот **${world.mascotName}** принёс нам необычную загадку. Тема нашего сегодняшнего урока — **"$topic"**.  
> Тот, кто поймёт её секрет, сможет без труда решать самые хитрые головоломки и станет настоящим волшебником знаний!  
> Кто готов отправиться в экспедицию за открытием? Поднимите руки! Отлично, открываем тетради — приключение начинается!»

*Совет Совёнка:* Интригующая интонация и прямой зрительный контакт включают произвольное внимание учеников на 100%! 🚀
''';
    }

    // 6. Физкультминутка
    if (lower.contains('физкульт') || lower.contains('разминк') || lower.contains('движен')) {
      return '''
🦉 **У-ху! Тематическая разминка для мира «${world.title}»**

*Тема урока:* **$topic**

*(Учитель просит детей встать около парт)*

> **1. «Достань до звёзд» (Потягивание, 30 сек):**  
> Мы потянемся на носочках высоко-высоко, пальчики растопырили, как лучики солнца. Вдох — носом, выдох — ртом!
>
> **2. «Хитрый маскот ${world.mascotName}» (Координация, 45 сек):**  
> Правая рука гладит животик по часовой стрелке, а левая рука аккуратно хлопает по макушке. А теперь поменяли ручки!
>
> **3. «Глазки-стрелочки» (Гимнастика для глаз по СанПиН):**  
> Посмотрели на кончик носа — перевели взгляд в окно на дальнее облако (повторить 4 раза).

*Совет Совёнка:* после такой разминки кора головного мозга насыщается кислородом, и дети готовы к сложным заданиям! ⭐
''';
    }

    // 7. Ловушка Незнайки
    if (lower.contains('ловушк') || lower.contains('незнайк') || lower.contains('ошибк')) {
      return '''
🦉 **Задание «Ловушка Незнайки» по теме «$topic»**

В наш мир «${world.title}» прибежал Незнайка и радостно кричит:  
> *«Я самый умный! Я знаю всё про тему "$topic" и утверждаю, что правила учить не надо — как слышится, так и пишется!»*

**Задание для ребят:**
1. Найдите ошибку в рассуждении Незнайки.
2. Назовите главное академическое правило нашей темы.
3. Помогите маскоту **${world.mascotName}** исправить карточку Незнайки и заработать победный кристалл! 💎
''';
    }

    // 8. ТРИЗ и проблемная задача
    if (mode == AssistantMode.triz || lower.contains('триз') || lower.contains('проблем')) {
      return '''
🦉 **ТРИЗ-задача: «Противоречие в мире ${world.title}»**

*Тема:* **$topic**

**Сюжетная завязка:**  
Маскот **${world.mascotName}** столкнулся с неожиданной задачей: предмет должен быть одновременно лёгким, чтобы его унести, но очень прочным, чтобы выдержать проверку на уроке!

**Вопросы для мозгового штурма детей:**
- Как решить эту задачу, используя свойства темы «$topic»?
- Что, если разделить предмет во времени или пространстве?
- Какое нестандартное применение мы можем предложить?

*Методическая ценность:* Развивает гибкость мышления по Г.С. Альтшуллеру и снимает страх неправильного ответа.
''';
    }

    // 9. Упрощение / адаптация
    if (lower.contains('упрост') || lower.contains('сложн') || lower.contains('адапт')) {
      return '''
🦉 **Методическая адаптация по принципу Пчёлко и Редозубова**

Чтобы помочь ученикам с трудностями в освоении темы **«$topic»**:

1. **Включите предметную наглядность:** перейдите от абстрактных символов к счётным палочкам, карточкам с рисунками YandexART или пуговицам.
2. **Разбейте алгоритм на 3 микро-шага:**  
   * Шаг 1: Вижу образец.  
   * Шаг 2: Проговариваю вслух шепотом.  
   * Шаг 3: Записываю в тетрадь.
3. **Парная работа:** посадите ученика с более уверенным соседом по парте для взаимного контроля по памятке.
''';
    }

    // 10. Общий академический ответ
    return '''
🦉 **Ответ Совёнка-Методиста**

По теме урока **«$topic»** в мире **«${world.title}»**:

* Рекомендую уделить 7–10 минут устному коллективному разбору с опорой на наглядность.
* Для закрепления используйте дидактические карточки с маскотом **${world.mascotName}**.
* На этапе рефлексии попросите ребят оценить свои силы с помощью 3 звёздочек ⭐⭐⭐.

Если нужно, я могу моментально составить:
• 💬 **Пост для родительского чата**  
• 📚 **3 уровня домашнего задания**  
• 🎮 **Сюжетный квест или игру**  
• 📝 **Экспресс-тест с ключами проверки**  
• 🤸 **Физкультминутку по СанПиН**  

Просто нажмите соответствующий чипс или напишите ваш вопрос!
''';
  }
