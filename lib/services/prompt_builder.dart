     4. [ЧИСЛОВОЙ ДОМИК / ГРАФОМОТОРНАЯ ДОРОЖКА]: домик состава числа (для математики) или непрерывная моторная дорожка с элементами букв.
     5. [ШИФРОВКА ИЛИ КРОССВОРД]: кодовая таблица, замена цифр значками, отгадывание ключевого слова.
     6. [КОРЗИНКА СЛОВ ДЛЯ СПРАВОК]: рамочка со словами/числами для подстановки в пропуски (никаких абстрактных формулировок!).
   - Возрастная адаптация формулировок:
     * Дошкольники (4–6 лет): короткие фразы, пиктограммы действий (👁️ Посмотри, ✏️ Обведи, 🎨 Раскрась, ✂️ Соедини).
     * 1 класс: крупный образец перед строкой, пунктирные направляющие для письма, косая линейка.
     * 2 класс: логические задачи, ТРИЗ-загадки, формулирование правила своими словами.
   - Уровень 1 (Старт): 2-3 базовых задания по образцу (первый пункт уже частично решён как подсказка) + «Линии для ответа: _______________________».
   - Уровень 2 (Практик): 3-4 прикладных задания с самостоятельным выбором и анализом.
   - Уровень 3 (Детектив Pro): 2 задачи повышенной сложности (олимпиадные, ТРИЗ, поиск спрятанной закономерности).
   - Интерактивный блок самооценки и настроения ученика (шкала успеха, смайлики, светофор).

4. РАЗВЕРНУТАЯ ДОМАШНЯЯ РАБОТА:
   - Детальная памятка для родителей: как поддержать ребенка, какие вопросы задать, как проверить без критики и давления.
   - Минимум 3 разнообразных смысловых блока заданий (тренировка, практика в быту/наблюдение, творческий вызов).

