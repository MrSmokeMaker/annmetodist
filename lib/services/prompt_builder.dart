   - ## ПАМЯТКА ДЛЯ РОДИТЕЛЕЙ:
     * 1-минутный скрипт: как родителю кратко объяснить суть задания без раздражения.
     * Ориентир времени: дошкольники — 10-15 мин, 1 класс — 15-20 мин, 2 класс — 20-25 мин.
