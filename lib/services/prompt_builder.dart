   - ### Блок 2: Исследование в быту (практическое задание в реальной домашней обстановке: посчитать ступени/посуду, найти букву на упаковке, измерить предмет шагами).
   - ### Блок 3: Семейный вызов / мини-игра (короткая игра вслух, викторина на кухне или загадка для всей семьи).
