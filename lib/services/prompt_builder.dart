  /// Извлекает эскиз меловой доски (Zero-Paper) из текста конспекта
  static String? extractChalkboardLayout(String content) {
    final bracketMatch = RegExp(r'\[CHALKBOARD_LAYOUT\]([\s\S]*?)\[/CHALKBOARD_LAYOUT\]', caseSensitive: false).firstMatch(content);
    if (bracketMatch != null) {
      final text = bracketMatch.group(1)?.trim();
      if (text != null && text.isNotEmpty) return text;
    }

    final regExp = RegExp(
      r'#+\s*(?:Эскиз(?:\s+оформления)?\s+меловой\s+доски|План\s+меловой\s+доски|Меловая\s+доска)[^\n]*\n([\s\S]*?)(?=(?:\n#+|\n```json|\Z))',
      caseSensitive: false,
    );
    final match = regExp.firstMatch(content);
    if (match != null) {
      final text = match.group(1)?.trim();
      if (text != null && text.isNotEmpty) return text;
    }
    return null;
  }

