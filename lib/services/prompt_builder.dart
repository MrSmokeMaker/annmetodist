ВАЖНЕЙШИЕ ПЕДАГОГИЧЕСКИЕ ТРЕБОВАНИЯ:
1. КАТЕГОРИЧЕСКИЙ ЗАПРЕТ НА КРАТКОСТЬ И ОБЩИЕ ФРАЗЫ (ЖИВАЯ ДРАМАТУРГИЯ УРОКА):
