/// Сервис для создания улучшенных шаблонов объяснения тем и диалогового взаимодействия с ребенком.
/// Содержит шаблоны для простого объяснения сложных тем, диалоговые сценарии и игровые приемы.
class ChildInteractionService {
  /// Шаблоны для простого объяснения тем ребенку по возрастным группам
  static Map<String, String> _ageGroupExplanations = {
    'preschool': '''
