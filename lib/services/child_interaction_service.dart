    'Что общего у этого с тем, что мы уже знаем?',
    'Как бы ты объяснил это своему другу?',
    'Что самое интересное в этом для тебя?',
    'Какой вопрос ты бы сам задал по этой теме?',
    'Что бы ты хотел узнать об этом еще?',
  ];

  /// Шаблоны похвалы и поддержки для разных ситуаций
  static Map<String, List<String>> _praiseTemplates = {
    'success': [
      'Молодец! Ты отлично справился!',
      'Здорово! Вижу, как старался!',
      'Отличная работа! Я тобой горжусь!',
      'Ты сделал это лучше, чем я ожидал!',
      'Замечательно! Продолжай в том же духе!',
    ],
    'difficulty': [
      'Я вижу, ты стараешься, это главное!',
      'Давай попробуем еще раз вместе, шаг за шагом.',
      'Все ошибаются, когда учатся новому. Это нормально!',
      'Ты уже сделал первый шаг — это уже успех!',
      'Посмотри, как много ты уже умеешь!',
    ],
    'creativity': [
      'Какой интересный подход!',
      'Я бы сам не догадался так сделать!',
      'Очень оригинальная идея!',
      'Ты думаешь нестандартно, это здорово!',
      'Такого объяснения я еще не слышал!',
    ]
  };

  /// Игровые приемы для вовлечения в учебный процесс
  static Map<String, List<String>> _gameTechniques = {
    'preschool': [
      'Волшебное превращение: представим, что мы волшебники и...',
      'Игра в прятки: давай найдем спрятанные буквы/цифры',
      'Соревнование на скорость: кто быстрее найдет все...',
      'Театр: разыграем сценку с участием...',
      'Квест: пройди путь и собери все элементы',
    ],
    'grade_1': [
      'Игра в детектива: найдем все подсказки',
      'Конструктор: собери слово/пример из частей',
      'Аукцион знаний: кто больше знает о...',
      'Путешествие по станциям: на каждой станции новое задание',
      'Секретная миссия: выполни задание и получи код',
    ],
    'grade_2': [
      'Проект: создай свой маленький проект по теме',
      'Дебаты: обсудим разные точки зрения',
      'Исследование: изучи и представь результаты',
      'Кроссворд/ребус: разгадай зашифрованное знание',
      'Создание игры: придумай свою игру по теме',
    ]
  };

  /// Получить рекомендации по объяснению для конкретной возрастной группы
  static String getExplanationGuidelines(String ageGroup) {
    return _ageGroupExplanations[ageGroup] ?? _ageGroupExplanations['grade_1']!;
  }

  /// Получить случайный вопрос для активации мышления
  static String getRandomThinkingQuestion() {
    final randomIndex = DateTime.now().microsecondsSinceEpoch % _thinkingQuestions.length;
    return _thinkingQuestions[randomIndex];
  }

  /// Получить шаблон похвалы по категории
  static String getPraiseTemplate(String category) {
    final templates = _praiseTemplates[category] ?? _praiseTemplates['success']!;
    final randomIndex = DateTime.now().microsecondsSinceEpoch % templates.length;
    return templates[randomIndex];
  }

  /// Получить игровой прием для возрастной группы
  static String getGameTechnique(String ageGroup) {
    final techniques = _gameTechniques[ageGroup] ?? _gameTechniques['grade_1']!;
    final randomIndex = DateTime.now().microsecondsSinceEpoch % techniques.length;
    return techniques[randomIndex];
  }

  /// Создать диалоговый сценарий для объяснения конкретной темы
  static String createDialogueScenario(String topic, String ageGroup, bool isComplex) {
    final ageLabel = ageGroup == 'preschool' ? 'дошкольник' : 
                    ageGroup == 'grade_1' ? 'первоклассник' : 'второклассник';
    
    final difficulty = isComplex ? 'сложную' : 'новую';
    
    return '''
Диалоговый сценарий для объяснения темы "$topic" ($ageLabel):

Учитель: "Сегодня мы узнаем кое-что очень интересное о $topic. Это как $difficulty игра!"
${getRandomThinkingQuestion()}

Ребенок: (предполагаемый ответ ребенка, который показывает его первоначальное понимание)

Учитель: "${getPraiseTemplate('success')} Давай посмотрим на это с другой стороны..."
(Использует пример из повседневной жизни)

Ребенок: (задает вопрос или выражает сомнение)

Учитель: "${getPraiseTemplate('difficulty')} ${getRandomThinkingQuestion()}"
(Использует наглядный пример или аналогию)

Ребенок: (проявляет понимание или интерес)

Учитель: "А теперь давай ${getGameTechnique(ageGroup)}! ${getPraiseTemplate('creativity')}"
''';
  }

  /// Создать простое объяснение темы для ребенка
  static String createSimpleExplanation(String topic, String subject, String ageGroup) {
    final ageDescription = ageGroup == 'preschool' ? 'маленькому ребенку' : 
                          ageGroup == 'grade_1' ? 'первокласснику' : 'второкласснику';
    
    final examples = {
      'Русский язык': [
        'Это как правила дорожного движения, только для слов',
        'Представь, что буквы — это строительные блоки для слов',
        'Это способ сделать так, чтобы все друг друга понимали',
      ],
      'Математика': [
        'Это как волшебные числа, которые помогают считать все вокруг',
        'Представь, что цифры — это друзья, которые вместе играют',
        'Это способ разгадывать загадки с помощью чисел',
      ],
      'Обучение чтению': [
        'Это как научиться разгадывать секретные коды из букв',
        'Представь, что буквы — это ключики к волшебным историям',
        'Это способ узнать, о чем говорят книжки',
      ],
      'Чистописание': [
        'Это как научиться красиво танцевать ручкой по бумаге',
        'Представь, что строчки — это дорожки для букв',
        'Это способ сделать так, чтобы твои мысли все могли прочитать',
      ],
    };

    final subjectExamples = examples[subject] ?? examples['Русский язык']!;
    final randomExample = subjectExamples[DateTime.now().microsecondsSinceEpoch % subjectExamples.length];
    
    return '''
Простое объяснение темы "$topic" для $ageDescription:

Это похоже на то, как $randomExample

Что это значит для тебя:
- Ты сможешь лучше понимать ${subject == 'Русский язык' ? 'книги и рассказы' : subject == 'Математика' ? 'сколько чего у тебя есть' : 'как устроен мир вокруг'}
- Это поможет тебе ${subject == 'Обучение чтению' ? 'самому читать любимые истории' : 'решать интересные задачки'}
- Ты будешь чувствовать себя ${subject == 'Чистописание' ? 'художником, создающим красивые буквы' : 'умным исследователем'}

Давай попробуем вместе! Я покажу тебе, как это работает, шаг за шагом.
''';
  }

  /// Создать список дополнительных заданий для домашней работы
  static List<String> createHomeworkAssignments(String topic, String subject, String ageGroup, int count) {
    final assignments = <String>[];
    
    final creativeTasks = [
      'Нарисуй, как ты представляешь себе тему "$topic"',
      'Придумай короткую историю, где используется то, что мы сегодня изучили',
      'Сделай коллаж из вырезок на тему "$topic"',
      'Придумай свою игру, которая поможет закрепить тему',
      'Напиши письмо другу, объясни ему тему "$topic" своими словами',
    ];
    
    final practicalTasks = {
      'Русский язык': [
        'Найди в книге/газете 5 примеров того, что мы сегодня изучали',
        'Составь 3 предложения с использованием новых правил',
        'Сделай карточки-подсказки для себя',
        'Проверь работу младшего брата/сестры (если есть)',
        'Запиши диктант на диктофон и потом проверь себя',
      ],
      'Математика': [
        'Посчитай, сколько предметов определенного цвета в комнате',
        'Придумай свою задачу на тему "$topic"',
        'Измерь длину/ширину 5 предметов в доме',
        'Создай свой магазин с ценами и покупками',
        'Построй график чего-нибудь за неделю',
      ],
      'Обучение чтению': [
        'Прочитай короткий рассказ и найди в нем изученные буквы/звуки',
        'Составь список слов на изученную тему',
        'Сделай азбуку из предметов, начинающихся на определенные буквы',
        'Запиши, как читаешь, и послушай себя',
        'Научи читать любимую игрушку',
      ],
      'Чистописание': [
        'Напиши красиво свое имя 5 раз разными способами',
        'Сделай открытку с красивыми надписями',
        'Нарисуй узор, используя элементы букв',
        'Напиши мини-сочинение, стараясь писать особенно красиво',
        'Создай свой шрифт из изученных элементов',
      ],
    };
    
    final gameTasks = [
      'Поиграй в игру "Найди лишнее" с родителями',
      'Устрой мини-олимпиаду по теме с семьей',
      'Сделай пазл из разрезанной карточки с заданием',
      'Поиграй в школу: ты учитель, а игрушки — ученики',
      'Придумай загадки на тему "$topic"',
    ];
    
    final subjectTasks = practicalTasks[subject] ?? practicalTasks['Русский язык']!;
    
    // Распределяем задания по типам
    final creativeCount = (count * 0.3).ceil(); // 30% творческих
    final practicalCount = (count * 0.5).ceil(); // 50% практических
    final gameCount = count - creativeCount - practicalCount; // остальные игровые
    
    for (int i = 0; i < creativeCount && i < creativeTasks.length; i++) {
      assignments.add(creativeTasks[i]);
    }
    
    for (int i = 0; i < practicalCount && i < subjectTasks.length; i++) {
      assignments.add(subjectTasks[i]);
    }
    
    for (int i = 0; i < gameCount && i < gameTasks.length; i++) {
      assignments.add(gameTasks[i]);
    }
    
    return assignments;
  }
}
